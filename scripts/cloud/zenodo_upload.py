def group_of(run: str) -> tuple[str, str]:   # same as scripts/package_release.py
    base = run.split("_")[0]
    if run.endswith("_zeroshot"):
        return "zeroshot", base
    if "_ct_" in run:
        return "colortransfer", base
    if run.rsplit("_", 1)[-1] in ("s1", "s2"):
        return "seeds", base
    return "lora", base


def zip_name(run: str) -> str:               # same as scripts/package_release.py
    group, base = group_of(run)
    rest = run[len(base):].strip("_").replace("zeroshot", "").replace("ct_", "").strip("_")
    return f"images_{group}_{base}" + (f"_{rest}" if rest else "") + ".zip"


def entries(run: str) -> list[tuple[Path, str, list]]:
    """(file, path inside the zip, index row) for every image of a run; cfg_4.0 is written cfg_4."""
    group, base = group_of(run)
    out = []
    for p in sorted(SAMPLES.glob(f"{run}/cfg_*/*/*.png")):
        cfg = f"{float(p.parent.parent.name[4:]):g}"
        cls = p.parent.name
        arc = f"{group}/{run}/cfg_{cfg}/{cls}/{p.name}"
        idx = int(re.search(r"_(\d+)\.png$", p.name).group(1))
        out.append((p, arc, [zip_name(run), arc, group, run, base, cfg, cls, idx]))
    return out


def build_zip(run: str, items: list) -> Path:
    zp = OUT / zip_name(run)
    done = OUT / (zp.name + ".done")
    if zp.exists() and done.exists() and done.read_text().strip() == str(len(items)):
        return zp
    part = OUT / (zp.name + ".part")
    with zipfile.ZipFile(part, "w", zipfile.ZIP_STORED, allowZip64=True) as z:   # PNGs do not compress
        for p, arc, _ in items:
            z.write(p, arc)
    part.rename(zp)
    done.write_text(str(len(items)))
    return zp


def md5(path: Path) -> str:
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 24), b""):
            h.update(chunk)
    return h.hexdigest()


def ok(r: requests.Response) -> requests.Response:
    """Stop with Zenodo's own message instead of a bare HTTPError."""
    if not r.ok:
        raise SystemExit(f"!! Zenodo {r.status_code} on {r.request.method} {r.url}: {r.text[:400]}\n"
                         "   401 = token wrong or revoked; 403 = token without the deposit:write scope")
    return r


def put(path: Path, url: str, token: str) -> str:
    """PUT one file with curl and return Zenodo's MD5. requests died with SSL EOF on multi-GB files when
    Zenodo dropped connections (Oct 2026); curl cuts an upload that stalls (< 20 kB/s for 3 min) and it is
    retried. The token reaches curl on stdin, not on its command line."""
    for attempt in range(1, 31):
        r = subprocess.run(["curl", "-sS", "--config", "-", "--speed-limit", "20000", "--speed-time", "180",
                            "--upload-file", str(path), "--write-out", "\n%{http_code} %{time_total} %{size_upload}", url],
                           input=f'header = "Authorization: Bearer {token}"\n', capture_output=True, text=True)
        body, _, tail = r.stdout.rpartition("\n")
        code, secs, sent = (tail.split() + ["", "0", "0"])[:3]
        if code.startswith("2"):
            return json.loads(body).get("checksum", "").removeprefix("md5:")
        if code.startswith("4") and code not in ("408", "429"):
            raise SystemExit(f"!! Zenodo {code} for {path.name}: {body[:400]}")
        print(f"  {path.name}: attempt {attempt} failed ({code} after {float(secs):.0f} s, "
              f"{float(sent) / 1e6:.0f} MB sent; {r.stderr.strip()[:120]}), retrying in 60 s", flush=True)
        time.sleep(60)
    raise SystemExit(f"!! {path.name} failed 30 times; rerun later (uploaded files are skipped)")


def deposition(headers: dict, stage: Path) -> dict:
    state = stage / "deposition.json"
    if state.exists():
        dep_id = json.loads(state.read_text())["id"]
        return ok(requests.get(f"{API}/deposit/depositions/{dep_id}", headers=headers, timeout=60)).json()
    r = ok(requests.post(f"{API}/deposit/depositions", headers=headers, json={"metadata": METADATA}, timeout=60))
    dep = r.json()
    state.write_text(json.dumps({"id": dep["id"]}))
    return dep


def main() -> None:
    ap = argparse.ArgumentParser(description="Zip all image runs and upload them to a Zenodo draft.")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--zip-only", action="store_true")
    ap.add_argument("--from-dir", type=Path, help="upload the zips, images_index.csv, and deposition.json already "
                                                   "in this folder (e.g. copied to a laptop) instead of zipping")
    args = ap.parse_args()
    missing = [f for f in SMALL_FILES if not (SMALL / f).exists()]
    if missing:
        raise SystemExit(f"!! missing in {SMALL}: {', '.join(missing)} (build them on the Mac with package_release.py)")
    if args.from_dir:
        stage = args.from_dir.expanduser()
        zips = sorted(stage.glob("images_*.zip"))
        with open(stage / "images_index.csv") as f:
            n_img = sum(1 for _ in f) - 1
        size = sum(p.stat().st_size for p in zips)
        print(f"  {len(zips)} zips, {n_img:,} images, {size / 1e9:.1f} GB in {stage}")
        if len(zips) != EXPECTED_RUNS or n_img != EXPECTED_IMAGES:
            raise SystemExit(f"!! expected {EXPECTED_RUNS} zips and {EXPECTED_IMAGES:,} images in {stage}")
        if args.dry_run:
            return
    else:
        stage = OUT
        zips = build_all(args)
        if not zips:
            return
    upload(stage, zips)


def build_all(args) -> list[Path]:
    """Zip experiments/samples into OUT (one zip per run); [] after --dry-run or --zip-only."""
    runs = sorted(d.name for d in SAMPLES.iterdir() if d.is_dir() and any(d.glob("cfg_*")))
    items = {r: entries(r) for r in runs}
    n_img = sum(len(v) for v in items.values())
    size = sum(p.stat().st_size for v in items.values() for p, _, _ in v)
    for r in runs:
        print(f"  {zip_name(r):42s} {len(items[r]):6,d} images")
    print(f"  {len(runs)} runs, {n_img:,} images, {size / 1e9:.1f} GB (+ small files)")
    if len(runs) != EXPECTED_RUNS or n_img != EXPECTED_IMAGES:
        raise SystemExit(f"!! expected {EXPECTED_RUNS} runs and {EXPECTED_IMAGES:,} images; check experiments/samples")
    if len(runs) + len(SMALL_FILES) + 1 > LIMIT_FILES or size > 0.98 * LIMIT_BYTES:
        raise SystemExit("!! above the Zenodo limit of 50 GB / 100 files per record")
    if args.dry_run:
        return []

    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "images_index.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["zip", "path", "group", "run", "model", "guidance", "class", "index"])
        for r in runs:
            w.writerows(row for _, _, row in items[r])
    zips = []
    for r in runs:
        zips.append(build_zip(r, items[r]))
        print(f"  zipped {zips[-1].name} ({zips[-1].stat().st_size / 1e9:.2f} GB)")
    return [] if args.zip_only else zips


def upload(stage: Path, zips: list[Path]) -> None:
    token = os.environ.get("ZENODO_TOKEN", "")
    if not token:
        raise SystemExit("Set ZENODO_TOKEN first:  read -rs ZENODO_TOKEN && export ZENODO_TOKEN")
    headers = {"Authorization": f"Bearer {token}"}
    dep = deposition(headers, stage)
    files_url = f"{API}/deposit/depositions/{dep['id']}/files"
    have = {f["filename"]: f for f in ok(requests.get(files_url, headers=headers, timeout=60)).json()}
    for path in [SMALL / f for f in SMALL_FILES] + [stage / "images_index.csv"] + zips:
        local = md5(path)
        old = have.get(path.name)
        if old and old["checksum"].removeprefix("md5:") == local:
            print(f"  already uploaded: {path.name}")
            continue
        if old:   # changed since it was uploaded (e.g. README.md after adding the DOI): replace it
            ok(requests.delete(f"{files_url}/{old['id']}", headers=headers, timeout=60))
        remote = put(path, f"{dep['links']['bucket']}/{path.name}", token)
        if remote != local:
            raise SystemExit(f"!! checksum mismatch for {path.name}: local {local}, Zenodo {remote}; rerun to retry")
        print(f"  uploaded {path.name} ({path.stat().st_size / 1e9:.2f} GB, md5 ok)", flush=True)
    dep = ok(requests.get(f"{API}/deposit/depositions/{dep['id']}", headers=headers, timeout=60)).json()
    doi = dep["metadata"].get("prereserve_doi", {}).get("doi", "(see the draft)")
    print(f"\nDRAFT ready, not published. Reserved DOI: {doi}")
    print(f"Review it here, then press Publish yourself: {SITE}/uploads/{dep['id']}")


if __name__ == "__main__":
    main()
